export function lookupCourseInfo(code: string): CatalogCourse {
  const cleanCode = code.toUpperCase().trim();
  if (BRACU_COURSE_CATALOG[cleanCode]) {
    return BRACU_COURSE_CATALOG[cleanCode];
  }
  return {
    code: cleanCode,
    name: `${cleanCode} Course`,
    credits: 3,
    hasLab: cleanCode.startsWith('CSE') || cleanCode.startsWith('PHY') || cleanCode.startsWith('EEE'),
    labCode: cleanCode + 'L',
    labCredits: 1,
    prerequisite: 'N/A',
    department: cleanCode.substring(0, 3),
  };
}

